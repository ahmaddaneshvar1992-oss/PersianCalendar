    const val DEFAULT_INDEX = 0 // تهران

    /** جستجوی نام شهر در فهرست (در صورت نبود، تهران) */
    fun findIndexByName(name: String): Int =
        list.indexOfFirst { it.name == name }.takeIf { it >= 0 } ?: DEFAULT_INDEX

    // ---------- نسخه ۱.۲: انتخاب استانی/شهرستانی + مکان‌یاب ----------

    /** فهرست استان‌ها به ترتیب ورود در data */
    val provinces: List<String> by lazy {
        list.map { it.province }.filter { it.isNotEmpty() }.distinct()
    }

    /** اندیس‌های شهرهای یک استان (به ترتیب فهرست اصلی) */
    fun indexesOfProvince(province: String): List<Int> =
        list.mapIndexedNotNull { i, c -> if (c.province == province) i else null }

    /** اولین اندیس شهر یک استان (برای انتخاب خودکار شهرستان پس از انتخاب استان) */
    fun firstIndexOfProvince(province: String): Int =
        list.indexOfFirst { it.province == province }.takeIf { it >= 0 } ?: DEFAULT_INDEX

    /** فاصله هوایی (کیلومتر) — فرمول هاورساین */
    fun distanceKm(lat1: Double, lng1: Double, lat2: Double, lng2: Double): Double {
        val r = Math.PI / 180.0
        val dLat = (lat2 - lat1) * r
        val dLng = (lng2 - lng1) * r
        val a = Math.sin(dLat / 2) * Math.sin(dLat / 2) +
                Math.cos(lat1 * r) * Math.cos(lat2 * r) *
                Math.sin(dLng / 2) * Math.sin(dLng / 2)
        return 2.0 * 6371.0 * Math.asin(Math.sqrt(a))
    }

    /** نزدیک‌ترین شهر به یک مختصات — برای مکان‌یاب GPS */
    fun nearest(lat: Double, lng: Double): Pair<Int, City> {
        var bestIdx = DEFAULT_INDEX
        var best = Double.MAX_VALUE
        list.forEachIndexed { i, c ->
            val d = distanceKm(lat, lng, c.lat, c.lng)
            if (d < best) {
                best = d
                bestIdx = i
            }
        }
        return bestIdx to list[bestIdx]
    }
